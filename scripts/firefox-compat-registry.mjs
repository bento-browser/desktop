// The firefox-compat registry: every Firefox member Bento depends on that is
// private or internal upstream (underscore and on_* methods, private-field
// accessors, prototype patches, lazy chrome globals, module URLs, chrome DOM
// ids, and event or markup contracts). Stable platform APIs (Services.*,
// PlacesUtils, SessionStore calls, <browser> navigation such as loadURI, the
// WebExtension API), prefs read by name, and the CSS selectors in
// bento-shell-mount.css are not listed.
//
// This module is repo tooling and is never shipped. Three things read it:
//   - scripts/check-firefox-compat.mjs greps a Firefox source tree for every
//     `at` pattern (pnpm run firefox:compat:engine) and checks the call sites.
//   - docs/firefox-core-touchpoints.md embeds a table generated from it
//     (node scripts/check-firefox-compat.mjs --write-docs).
//   - A test keeps the compact probe list in the @bento-firefox-compat section of
//     src/browser/base/content/bento-shell-mount.js equal to the entries whose
//     probe is R. Adding a runtime-probable entry means adding its id to that
//     list too.
//
// Entry fields:
//   id      unique. 'Owner.member' for members, the id for elements, the URL
//           for modules. Owner is a window global (a path such as
//           Element.prototype walks its interface object), or
//           MozBrowser.prototype / MozTabbrowserTab (the roots the mount probe
//           resolves specially).
//   kind    method | member | element | module | source.
//   how     wraps | overrides | calls | reads | writes | queries | listens |
//           dispatches | imports.
//   probe   R: probed in a live window by the mount, passively. The probe
//           reads properties through descriptors and never calls an accessor
//           or imports a module that is not loaded, so a lazy global or module
//           is never forced to load. A member whose descriptor exists anywhere
//           on the prototype chain, data or accessor, is present (a method
//           found as an accessor cannot be call-checked and counts as
//           present). An owner that is absent is missing, one that is still an
//           untriggered accessor (or a module that is not loaded yet) is
//           deferred. E: engine check only (events, markup,
//           instance fields assigned late, elements inside an <html:template>
//           until their owner expands it, members of documents other than the
//           browser window, user-customizable toolbar items); kind is source.
//   native  Required when how is wraps or overrides: Bento replaces or shadows
//           the member, so a plain presence probe would find Bento's own copy.
//           'note': the patch site calls bentoCompatNoteNative(id, original)
//           before replacing, and the probe judges that recorded original.
//           'proto': the probe looks the member up on the owner's prototype,
//           which Bento's per-instance writes do not touch.
//   sites   where Bento touches it: 'name' is a token in the mount script,
//           'path#name' a token in another repo file.
//   use     what Bento does with it.
//   exports module entries: the one name the module must export.
//   at      [Firefox source file, regex (multiline), line in vanilla Firefox at
//           BASELINE]. The line is informational; the regex must match in the
//           engine tree.
//   reg     optional [file, regex] proving a resource:// module is registered.

