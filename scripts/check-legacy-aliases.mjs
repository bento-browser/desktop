/* global console, process */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  countLegacyAliases,
  evaluateCounts,
  formatCap,
  parseCap,
  refreshCap,
} from './legacy-aliases.mjs';

// Legacy alias ratchet for the shell's CSS (see legacy-aliases.mjs). The committed cap is
// .legacy-alias-cap.json: the check fails when a file, or the total, uses more legacy
// aliases than the cap allows.
//
//   node scripts/check-legacy-aliases.mjs                   check against the cap
//   node scripts/check-legacy-aliases.mjs --write-cap       lower the cap to the current counts
//       (the first run, with no cap file, records them as the starting cap); refuses to raise a file unless it is named with --accept-growth <file> (repeatable,
//       a path relative to the repo root).
//   --root <dir> scans another tree (used by the tests).
const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCAN_DIR = 'extensions/bento-shell/src';
// Generated by scripts/sync-theme-presets.mjs: it defines the aliases rather than using them.
const SKIPPED_DIR = 'extensions/bento-shell/src/theme/presets';
const CAP_FILE = '.legacy-alias-cap.json';

function readArgs(argv) {
  const args = { root: REPO_ROOT, writeCap: false, acceptGrowth: [] };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--write-cap') args.writeCap = true;
    else if (argument === '--accept-growth' || argument === '--root') {
      const value = argv[(index += 1)];
      if (!value || value.startsWith('--')) throw new Error(`${argument} needs a value`);
      if (argument === '--root') args.root = resolve(value);
      else args.acceptGrowth.push(value);
    } else throw new Error(`Unknown option ${argument}`);
  }
  return args;
}

function cssFiles(directory, root) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    const relativePath = relative(root, path).split('\\').join('/');
    if (entry.isDirectory()) return relativePath === SKIPPED_DIR ? [] : cssFiles(path, root);
    return entry.name.endsWith('.css') ? [relativePath] : [];
  });
}

/** `{ file: count }` for every scanned stylesheet that uses at least one legacy alias. */
function measure(root) {
  const measured = {};
  for (const file of cssFiles(resolve(root, SCAN_DIR), root).sort()) {
    const count = countLegacyAliases(readFileSync(resolve(root, file), 'utf8'));
    if (count > 0) measured[file] = count;
  }
  return measured;
}

function main() {
  const { root, writeCap, acceptGrowth } = readArgs(process.argv.slice(2));
  const capPath = resolve(root, CAP_FILE);
  const measured = measure(root);
  const previous = existsSync(capPath) ? parseCap(readFileSync(capPath, 'utf8')) : null;

  if (writeCap) {
    // Without a cap file the current counts become the first cap.
    const { next, lowered, raised, refused } = refreshCap({
      previous: previous?.files ?? {},
      measured,
      acceptGrowth: previous ? acceptGrowth : Object.keys(measured),
    });
    writeFileSync(capPath, formatCap(next));
    console.log(
      `Wrote ${CAP_FILE}: ${lowered.length} lowered, ${raised.length} raised, ` +
        `${refused.length} refused`,
    );
    for (const file of refused) {
      console.log(
        `  refused to raise ${file} (${previous?.files[file] ?? 0} -> ${measured[file]}); ` +
          'migrate the new uses or pass --accept-growth <file>',
      );
    }
    process.exit(refused.length > 0 ? 1 : 0);
  }

  if (!previous)
    throw new Error(`Missing ${CAP_FILE}; run with --write-cap to record the current counts`);
  const result = evaluateCounts({ measured, cap: previous });
  for (const { file, count, allowed } of result.grew) {
    console.log(`FAIL ${file}: ${count} legacy alias uses, cap ${allowed}`);
  }
  if (result.totalGrew) {
    console.log(`FAIL total: ${result.total} legacy alias uses, cap ${previous.total}`);
  }
  if (result.failed) {
    console.log(
      'Use public Mux semantic tokens or --bento-* tokens in new CSS (docs/mux-ui-component-customisations.md).',
    );
    process.exit(1);
  }
  console.log(`OK legacy aliases: ${result.total} uses / cap ${previous.total}`);
  if (result.shrunk.length > 0) {
    console.log(
      `  note: ${result.shrunk.length} file(s) are below their cap; ` +
        'run node scripts/check-legacy-aliases.mjs --write-cap to lock in the gain',
    );
  }
}

try {
  main();
} catch (error) {
  console.error(`check-legacy-aliases: ${error.message}`);
  process.exit(1);
}
