#!/usr/bin/env node
// Merged twins for the mode flip fade (docs/technical/theming.md, "Mode flip fade").
//
// The fade's catch-all rule sets the `transition` shorthand on every element while data-bento-mode-fade
// is present, which REPLACES the element's own list: a running `opacity` or `transform` transition of a
// panel, row or overlay is cancelled (it jumps to its end value), and a non-colour transition that
// would start during the fade does not run. A twin keeps them: for each Bento rule that declares a
// non-colour transition, the fade layer repeats that rule's selectors under the fade attribute with the
// rule's own non-colour entries and the shared colour list (`--bento-mode-fade-colours`, one custom
// property per stylesheet that holds the catch-all's entries), so colours fade on the shared pair with the
// shared delay and everything else keeps its own duration and easing, undelayed.
// The distinct `settle` value zeros only the shared colour entries (duration and delay),
// leaving the same twins/non-colour entries in force. Callers install it before the final
// mode write and flush styles before removing it.
//
// The twins are generated: `node scripts/fade-twins.mjs` rewrites the marked regions of the two
// stylesheets that hold a catch-all, and `scripts/mount-fade-css.test.mjs` fails when they are stale,
// which is also the check that a new non-colour transition has a twin. A rule inside
// `prefers-reduced-motion: reduce` is skipped (the fade does not run there).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { splitTopLevelBlocks } from '../extensions/bento-shell/css-blocks.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const BEGIN = '/* fade-twins:begin (generated by scripts/fade-twins.mjs, do not edit) */';
export const END = '/* fade-twins:end */';
export const COLOURS_PROPERTY = '--bento-mode-fade-colours';
// The same list without `color`, for elements whose text colour is inherited and must follow their parent's
// transition: an own `color` transition there is redundant and is cancelled when Firefox rewrites the
// element's classes in the panel reconcile, and a restart after that lags the parent's fade.
export const INHERITED_PROPERTY = '--bento-mode-fade-colours-inherited';
const ATTR = 'data-bento-mode-fade';

function walk(dir, skip) {
  const files = [];
  for (const entry of readdirSync(resolve(REPO, dir), { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (skip(path)) continue;
    if (entry.isDirectory()) files.push(...walk(path, skip));
    else if (path.endsWith('.css')) files.push(path);
  }
  return files.sort();
}

/** The two stylesheets that hold a catch-all, the layer it is in, and the rules that twin into it. */
export const TARGETS = [
  {
    sheet: 'src/browser/base/content/bento-chrome-theme.css',
    layer: '@layer bento.chrome-theme.fade',
    sources: () => ['src/browser/base/content/bento-shell-mount.css'],
    inheritColour: ['.browserSidebarContainer', '.bento-panel-header'],
  },
  {
    sheet: 'extensions/bento-shell/src/theme/document-base.css',
    layer: '@layer bento.mode-fade',
    // Footer fill keeps its rail spring during an ordinary fade, but settles with colours.
    settleCarriers: ['--bento-footer-fill'],
    sources: () =>
      walk(
        'extensions/bento-shell/src',
        (path) => path.includes('/theme/presets') || path.endsWith('/theme/document-base.css'),
      ),
  },
];

/** Longhands of `border-color`, which the catch-all lists as the shorthand: their own entries lose to it. */
const COLOUR_LONGHANDS = new Set([
  'border-top-color',
  'border-right-color',
  'border-bottom-color',
  'border-left-color',
]);

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '');

/** Split on top-level occurrences of `separator` (outside parentheses, brackets and strings). */
export function splitTop(text, separator) {
  const parts = [];
  let depth = 0;
  let quote = null;
  let start = 0;
  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (quote) {
      if (character === '\\') index += 1;
      else if (character === quote) quote = null;
    } else if (character === '"' || character === "'") quote = character;
    else if (character === '(' || character === '[') depth += 1;
    else if (character === ')' || character === ']') depth -= 1;
    else if (depth === 0 && separator.test(character)) {
      parts.push(text.slice(start, index));
      start = index + 1;
    }
  }
  parts.push(text.slice(start));
  return parts.map((part) => part.trim()).filter(Boolean);
}

/** The property an entry of a transition list names (its first token). */
const entryProperty = (entry) => splitTop(entry, /\s/)[0];

/** The entries (property, then timing) of the catch-all's colour list in `css`. */
export function fadeEntries(css) {
  const block = splitTopLevelBlocks(stripComments(css))
    .flatMap(({ prelude, body }) => (prelude.startsWith('@layer') ? splitTopLevelBlocks(body) : []))
    .find(({ prelude, body }) => prelude.includes(`:root[${ATTR}] *`) && body.includes('transition:'));
  if (!block) throw new Error('no catch-all rule');
  const value = block.body.split('transition:')[1].split('!important')[0];
  return splitTop(value, /,/).map((entry) => entry.replace(/\s+/g, ' '));
}

function declaration(body, name) {
  const match = new RegExp(`(?:^|[;{\\s])${name}\\s*:\\s*([^;]+?)\\s*(?:;|$)`).exec(body);
  return match ? match[1].replace(/\s*!important\s*$/, '').replace(/\s+/g, ' ') : null;
}

/** Own entries of a rule body: the `transition` shorthand, or the longhands zipped, or null. */
function ownEntries(body) {
  const shorthand = declaration(body, 'transition');
  if (shorthand !== null) return shorthand === 'none' ? [] : splitTop(shorthand, /,/);
  const properties = declaration(body, 'transition-property');
  if (properties === null) return null;
  const lists = ['transition-duration', 'transition-timing-function', 'transition-delay'].map(
    (name) => {
      const value = declaration(body, name);
      return value === null ? [] : splitTop(value, /,/);
    },
  );
  return splitTop(properties, /,/).map((property, index) =>
    [property, ...lists.map((list) => list[index % list.length]).filter(Boolean)].join(' '),
  );
}

function* rules(css, context = []) {
  for (const { prelude, body } of splitTopLevelBlocks(css)) {
    if (/^@(layer|media|supports|container)\b/.test(prelude)) {
      yield* rules(body, prelude.startsWith('@layer') ? context : [...context, prelude]);
    } else if (!prelude.startsWith('@') && !/^(\d+%|from|to)\b/.test(prelude)) {
      yield { context, selector: prelude, body };
    }
  }
}

/** `[attr] .a` for a descendant selector, `:root[attr]...` for one that starts at the root: +1 attribute. */
function underFade(selector) {
  const root = /^(:root|html)\b/.exec(selector);
  if (!root) return `[${ATTR}] ${selector}`;
  return `${root[1]}[${ATTR}]${selector.slice(root[1].length)}`;
}

/**
 * The twin rules for one stylesheet's source: `{ context, selectors, own, source }` per rule that
 * declares a transition outside reduced motion. `own` is the list of entries that stay (the fade
 * list replaces the rest), empty for `none` and colour-only rules.
 */
export function twinRules(css, fadeProperties) {
  const out = [];
  for (const rule of rules(stripComments(css))) {
    if (rule.context.some((c) => c.includes('prefers-reduced-motion'))) continue;
    const entries = ownEntries(rule.body);
    if (entries === null) continue;
    const own = entries.filter((entry) => {
      const property = entryProperty(entry);
      return !fadeProperties.has(property) && !COLOUR_LONGHANDS.has(property);
    });
    const selectors = splitTop(rule.selector, /,/).map((s) => s.replace(/\s+/g, ' '));
    const isNone = declaration(rule.body, 'transition') === 'none';
    // A colour-only list is what the catch-all already does; `none` stays to override a twin below it.
    if (!own.length && !isNone) continue;
    out.push({ context: rule.context, selectors, own });
  }
  return out;
}

export function twinText(rulesList, inheritColour = []) {
  const lines = [];
  for (const { context, selectors, own } of rulesList) {
    const head = selectors.map(underFade).join(',\n');
    const colours = selectors.every((selector) => inheritColour.includes(selector)) ? INHERITED_PROPERTY : COLOURS_PROPERTY;
    const value = [...own, `var(${colours})`].join(',\n    ');
    let text = `${head} {\n  transition:\n    ${value} !important;\n}`;
    for (const at of [...context].reverse()) text = `${at} {\n${text.replace(/^/gm, '  ')}\n}`;
    lines.push(text);
  }
  return lines.join('\n\n');
}

/** The generated region of one target: the colour list property and every twin. */
export function generatedRegion(target) {
  const sheetCss = readFileSync(resolve(REPO, target.sheet), 'utf8');
  const entries = fadeEntries(sheetCss);
  const fadeProperties = new Set(entries.map(entryProperty));
  const twins = target
    .sources()
    .flatMap((path) =>
      twinRules(readFileSync(resolve(REPO, path), 'utf8'), fadeProperties).map((rule) => ({
        ...rule,
        path,
      })),
    );
  const inheritColour = target.inheritColour ?? [];
  const inherited = entries.filter((entry) => entryProperty(entry) !== 'color');
  const colours = `:root[${ATTR}] {\n  ${COLOURS_PROPERTY}:\n    ${entries.join(',\n    ')};${
    inheritColour.length ? `\n  ${INHERITED_PROPERTY}:\n    ${inherited.join(',\n    ')};` : ''
  }\n}`;
  const zeroTime = 'calc(var(--muxui-semantic-motion-state-transition-duration) * 0)';
  const settled = [...new Set([...entries.map(entryProperty), ...(target.settleCarriers ?? [])])]
    .map((property) => `${property} ${zeroTime} var(--muxui-semantic-motion-state-transition-easing) ${zeroTime}`);
  const settleSelector = `:root[${ATTR}='settle']`;
  const settleColours = `${settleSelector} {\n  ${COLOURS_PROPERTY}:\n    ${settled.join(',\n    ')};${
    // Zero-time color creates no redundant fade, and must override any retained `all`.
    inheritColour.length ? `\n  ${INHERITED_PROPERTY}:\n    ${settled.join(',\n    ')};` : ''
  }\n}`;
  // This has the same specificity as the normal catch-all and precedes the twins:
  // an own `all` stays first, then explicit instant colours win by list order.
  const settleCatchAll = [settleSelector, `${settleSelector} *`, `${settleSelector} *::before`, `${settleSelector} *::after`]
    .join(',\n') + ` {\n  transition: var(${COLOURS_PROPERTY}) !important;\n}`;
  let previous = null;
  const sections = [];
  const twinned = new Set();
  for (const rule of twins) {
    if (rule.path !== previous) sections.push(`/* ${rule.path} */`);
    previous = rule.path;
    for (const selector of rule.selectors) twinned.add(selector);
    sections.push(twinText([rule], inheritColour));
  }
  // An inherited-colour element without a non-colour transition of its own still needs its rule.
  const extra = inheritColour.filter((selector) => !twinned.has(selector));
  if (extra.length) {
    sections.push('/* elements whose text colour follows their parent (see INHERITED_PROPERTY) */');
    for (const selector of extra) sections.push(twinText([{ context: [], selectors: [selector], own: [] }], inheritColour));
  }
  return [BEGIN, colours, settleColours, settleCatchAll, ...sections, END].join('\n\n');
}

/** The sheet text with its generated region (re)written inside the layer, after the catch-all. */
export function withRegion(target, region) {
  const css = readFileSync(resolve(REPO, target.sheet), 'utf8');
  const indent = (text) => text.replace(/^(?=.)/gm, '  ');
  const generated = indent(region);
  const begin = css.indexOf(`  ${BEGIN}`);
  if (begin >= 0) {
    const end = css.indexOf(END, begin) + END.length;
    return css.slice(0, begin) + generated + css.slice(end);
  }
  // First time: before the closing brace of the layer that holds the catch-all.
  const layerStart = css.indexOf(`${target.layer} {`);
  if (layerStart < 0) throw new Error(`${target.sheet} has no ${target.layer}`);
  const open = css.indexOf('{', layerStart);
  let depth = 0;
  let close = -1;
  for (let index = open; index < css.length; index += 1) {
    if (css[index] === '{') depth += 1;
    else if (css[index] === '}' && --depth === 0) {
      close = index;
      break;
    }
  }
  return `${css.slice(0, close).trimEnd()}\n\n${generated}\n${css.slice(close)}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const target of TARGETS) {
    writeFileSync(resolve(REPO, target.sheet), withRegion(target, generatedRegion(target)));
    console.log(`fade-twins: wrote ${target.sheet}`);
  }
}
